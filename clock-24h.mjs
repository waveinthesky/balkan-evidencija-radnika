import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1280,height:950},locale:'en-US'});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',async d=>d.accept());
await page.route('**/admin-firebase.js*',r=>r.fulfill({status:200,contentType:'application/javascript',body:"(async()=>{await window.BALKAN_V6.boot();document.getElementById('v6Login').style.display='none';window.__CLOCK_READY=true})().catch(e=>window.__CLOCK_ERROR=String(e))"}));
await page.goto('http://127.0.0.1:8765/admin.html',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>window.__CLOCK_READY||window.__CLOCK_ERROR);
assert.equal(await page.evaluate(()=>window.__CLOCK_ERROR||''),'','App boot');
await page.getByRole('button',{name:/Objekti/}).first().click();
await page.locator('[data-location-edit="m1"]').click();
const form=page.locator('#locationForm');
for(const field of ['open','close','firstStart','firstEnd','secondStart','secondEnd']){
 const input=form.locator('input[name="'+field+'"]');
 assert.equal(await input.getAttribute('type'),'text','Clock is text, never localized picker: '+field);
 assert.equal(await input.getAttribute('placeholder'),'HH:MM','Placeholder for '+field);
}
await form.locator('input[name=from]').fill('2026-11-01');
await form.locator('input[name=open]').fill('07:00');
await form.locator('input[name=close]').fill('21:00');
await form.locator('input[name=firstStart]').fill('07:00');
await form.locator('input[name=firstEnd]').fill('1430');
await form.locator('input[name=secondStart]').click();
assert.equal(await form.locator('input[name=firstEnd]').inputValue(),'14:30','Convenient 1430 -> 14:30');
await form.locator('input[name=secondStart]').fill('14:30');
await form.locator('input[name=secondEnd]').fill('21:00');
await form.locator('input[name=secondEnd]').fill('25:00');
assert.equal(await form.locator('input[name=secondEnd]').evaluate(e=>e.checkValidity()),false,'25:00 invalid');
await form.locator('input[name=secondEnd]').fill('21:00');
await form.locator('button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('#locationForm')===null);
const schedule=await page.evaluate(()=>window.BALKAN_V6.state().locations.find(l=>l.id==='m1').schedules.find(s=>s.from==='2026-11-01'));
assert.equal(schedule.firstEnd,'14:30');
assert.equal(schedule.secondStart,'14:30');
assert.equal(schedule.secondEnd,'21:00');
await page.getByRole('button',{name:/Radnici/}).first().click();
await page.getByRole('button',{name:/Dodaj radnika/}).first().click();
const worker=page.locator('#workerForm');
assert.equal(await worker.locator('input[name=shiftStart]').getAttribute('type'),'text');
await worker.locator('input[name=name]').fill('Sati Testni');
await worker.locator('input[name=barcode]').fill('CLOCK_TEST_001');
await worker.locator('input[name=hiredAt]').fill('2026-10-15');
await worker.locator('input[name=shiftStart]').fill('14:30');
await worker.locator('button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('#workerForm')===null);
assert.equal(await page.evaluate(()=>window.BALKAN_V6.state().employees.find(e=>e.name==='Sati Testni')?.shiftStart),'14:30');
await page.getByRole('button',{name:/Praznici i odsustva/}).first().click();
await page.getByRole('button',{name:/Evidencija radnika/}).first().click();
const manual=page.locator('#manualForm');
await manual.locator('select[name=type]').selectOption('IN');
assert.equal(await manual.locator('input[name=time]').getAttribute('type'),'text','Manual time uses 24h HH:MM');
assert.equal(await manual.locator('input[name=time]').getAttribute('placeholder'),'HH:MM');
assert.equal(errors.length,0,errors.join(' | '));
console.log('PASS 24H en-US browser: 9 text-only clock inputs, auto 1430 to 14:30, invalid 25:00 blocked, future shifts and employee time persisted');
await browser.close();
