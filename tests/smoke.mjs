import { chromium } from 'playwright';
import assert from 'node:assert/strict';

const browser=await chromium.launch({headless:true});
const mobile=!!process.env.TEST_MOBILE;
const context=await browser.newContext({viewport:mobile?{width:390,height:844}:{width:1440,height:960}});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push('PAGE '+e.message));
page.on('console',m=>{if(m.type()==='error')errors.push('CONSOLE '+m.text())});
page.on('dialog',async dialog=>await dialog.accept());
await page.route('**/admin-firebase.js*',route=>route.fulfill({status:200,contentType:'application/javascript',
body:`(async()=>{const api=window.BALKAN_V6;await api.boot();document.getElementById('v6Login').style.display='none';window.__AUDIT_BOOTED=true})().catch(e=>{window.__AUDIT_ERROR=e.stack||String(e);console.error('Audit boot:',e);})`
}));
await page.goto('http://127.0.0.1:8765/admin.html',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>window.__AUDIT_BOOTED||window.__AUDIT_ERROR,{timeout:15000});
assert.equal(await page.evaluate(()=>window.__AUDIT_ERROR||''),'','Admin bootstrap');
await page.getByRole('button',{name:/Radnici/}).first().click();
await page.getByRole('button',{name:/Dodaj radnika/}).first().click();
assert.equal(await page.locator('#workerForm').count(),1,'Worker form exists');
await page.locator('#workerForm input[name=name]').fill('Testni Radnik Za Audit');
await page.locator('#workerForm input[name=barcode]').fill('TEST-AUDIT-999');
await page.locator('#workerForm input[name=hiredAt]').fill('2025-01-01');
await page.locator('#workerForm button[type=submit]').click();
await page.waitForTimeout(500);
assert.ok(await page.getByText('Testni Radnik Za Audit').count(),'Saved worker visible');
await page.getByRole('button',{name:/Kalendar/}).first().click();
await page.locator('select[data-field=calM]').selectOption('10');
await page.locator('input[data-field=calY]').fill('2026');
await page.locator('input[data-field=calY]').dispatchEvent('change');
await page.waitForTimeout(250);
assert.equal(await page.locator('table.calendar thead th').count(),33,'31 calendar dates plus name and total');
assert.ok(await page.locator('table.calendar button.cell').count()>=31,'Calendar cells visible');
const layout=await page.evaluate(()=>{
 let a=document.querySelector('.balkan-month-grid'),b=document.querySelector('table.calendar');
 return {panel:a.clientWidth,table:b.getBoundingClientRect().width,scroll:a.scrollWidth};
});
assert.ok(layout.scroll<=layout.panel+3,'No horizontal scrolling in month calendar: '+JSON.stringify(layout));
const first=page.locator('table.calendar button.cell.N').first();
assert.ok(await first.count(),'Past day without scan');
const date=await first.getAttribute('data-day'),emp=await first.getAttribute('data-emp');
await first.click();
await page.waitForTimeout(200);
assert.ok(await page.locator('table.calendar button.cell.P[data-day="'+date+'"][data-emp="'+emp+'"]').count(),'P on first click');
const statusN=page.locator('table.calendar button.cell.P[data-day="'+date+'"][data-emp="'+emp+'"]');
await statusN.click();
await page.waitForTimeout(200);
assert.ok(await page.locator('table.calendar button.cell.N[data-day="'+date+'"][data-emp="'+emp+'"]').count(),'N on second click');
const top=await page.evaluate(()=>document.querySelector('.balkan-month-grid').getBoundingClientRect().top);
const details=await page.locator('#dayPanel').count();
assert.ok(details===1,'Day detail below calendar exists');
await page.getByRole('button',{name:/Praznici i odsustva/}).first().click();
await page.getByRole('button',{name:/Praznik/}).first().click();
assert.equal(await page.locator('#holidayForm input[name=endDate]').count(),1,'Date range field exists');
await page.locator('#holidayForm input[name=label]').fill('Testni vjerski praznik');
await page.locator('#holidayForm input[name=date]').fill('2026-10-20');
await page.locator('#holidayForm input[name=endDate]').fill('2026-10-22');
await page.locator('#holidayForm select[name=type]').selectOption('religious');
await page.locator('#holidayForm button[type=submit]').click();
await page.waitForTimeout(250);
assert.ok(await page.getByText('Testni vjerski praznik').count(),'Saved holiday listed');
await page.getByRole('button',{name:/Kalendar/}).first().click();
const vh=page.locator('table.calendar button.cell.VH');
assert.ok(await vh.count()>=3,'Range produces three religious holiday days');
await page.getByRole('button',{name:/Izvještaji/}).first().click();
await page.waitForTimeout(250);
assert.ok(await page.getByText('Sedmični pregled sati').count(),'Weekly report section');
assert.ok(await page.getByText(/Stvarno odrađeno/).count(),'Worked-hours section');
await page.reload({waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>window.__AUDIT_BOOTED||window.__AUDIT_ERROR,{timeout:15000});
assert.equal(await page.evaluate(()=>window.__AUDIT_ERROR||''),'','Admin reload');
await page.getByRole('button',{name:/Radnici/}).first().click();
assert.ok(await page.getByText('Testni Radnik Za Audit').count(),'Worker remains after reload');
assert.equal(errors.length,0,'JavaScript errors: '+errors.join(' | '));
console.log('PASS '+(mobile?'MOBILE':'DESKTOP')+' browser test: forms, save, calendar full month, P↔N click, detail, holiday range, reports, reload');
console.log('Layout:',JSON.stringify(layout));
await browser.close();
