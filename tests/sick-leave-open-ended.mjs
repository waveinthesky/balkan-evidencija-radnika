import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:950}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',async d=>{if(d.type()==='alert')throw Error('Unexpected alert: '+d.message());await d.accept()});
await page.route('**/admin-firebase.js*',r=>r.fulfill({status:200,contentType:'application/javascript',body:"(async()=>{await window.BALKAN_V6.boot();document.getElementById('v6Login').style.display='none';window.__AUDIT_BOOTED=true})().catch(e=>window.__AUDIT_ERROR=String(e))"}));
await page.goto('http://127.0.0.1:8765/admin.html',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>window.__AUDIT_BOOTED||window.__AUDIT_ERROR);
assert.equal(await page.evaluate(()=>window.__AUDIT_ERROR||''),'');
await page.evaluate(()=>{
 const s=window.BALKAN_V6.state();
 s.locations[0].schedules.push({id:'sick-sc',from:'2026-01-01',open:'07:00',close:'21:00',firstStart:'08:00',firstEnd:'14:00',secondStart:'14:00',secondEnd:'21:00',grace:0,days:[1,2,3,4,5,6]});
 s.employees.push({id:'sick-emp',name:'Bolovanje Testni',active:true,barcode:'SICK_TEST',defaultLocationId:'m1',defaultShift:'first',attendanceFrom:'2026-01-01',hiredAt:'2026-01-01',assignments:[{from:'2026-01-01',locationId:'m1'}],leaveQuotaByYear:{'2026':24},leaveCarryByYear:{'2026':0}});
 s.employees.push({id:'leave-empty',name:'Odmor Bez Prava',active:true,barcode:'EMPTY_QUOTA',defaultLocationId:'m1',defaultShift:'first',attendanceFrom:'2026-01-01',hiredAt:'2026-01-01',assignments:[{from:'2026-01-01',locationId:'m1'}]});
 s.overrides.push({id:'go-used',date:'2026-02-02',empId:'sick-emp',locId:'m1',status:'GO'});
 s.overrides.push({id:'go-past',date:'2026-02-03',empId:'leave-empty',locId:'m1',status:'GO'});
 window.BALKAN_V6.render();
});
await page.getByRole('button',{name:/Radnici/}).first().click();
const quotaRow=page.locator('tr').filter({hasText:'Odmor Bez Prava'}).first();
assert.match(await quotaRow.innerText(),/Procjena|potvrdi pravo|Unesi pravo/i,'Nepotvrđen godišnji fond je jasno označen kao informativan');
assert.ok((await quotaRow.innerText()).includes('1'),'Manual GO day counted even without quota');
await page.locator('tr').filter({hasText:'Bolovanje Testni'}).locator('[data-sick-worker]').click();
assert.ok(await page.locator('#balkanSickLeaveForm').count(),'Sick leave form opened');
await page.locator('#balkanSickLeaveForm input[name=from]').fill('2026-03-01');
assert.equal(await page.locator('#balkanSickLeaveForm input[name=to]').inputValue(),'','Open ended leave');
await page.locator('#balkanSickLeaveForm button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('#balkanSickLeaveForm')===null);
assert.equal(await page.evaluate(()=>window.BALKAN_V6.state().employees.find(e=>e.id==='sick-emp').sickLeaves.length),1,'Saved range');
assert.ok((await page.locator('tr').filter({hasText:'Bolovanje Testni'}).first().innerText()).includes('Na bolovanju'),'Worker remains in employee management');
await page.getByRole('button',{name:/Pregled/}).first().click();
assert.ok(await page.getByText('Na bolovanju – bez upozorenja o izostanku').count(),'Dashboard separate sick list');
const dash=await page.locator('body').innerText();
assert.ok(!dash.includes('Bolovanje Testni\nPrva smjena'),'Sick worker not in active shift table');
await page.getByRole('button',{name:/Kalendar/}).first().click();
const now=new Date();
const currentY=String(now.getFullYear()), currentM=String(now.getMonth()+1);
await page.locator('select[data-field=calM]').selectOption(currentM);
await page.locator('input[data-field=calY]').fill(currentY);
await page.locator('input[data-field=calY]').dispatchEvent('change');
assert.ok(await page.getByText('Radnici na bolovanju').count(),'Calendar sick info');
assert.ok(await page.getByText('Bolovanje Testni').count(),'Sick info visible');
assert.equal(await page.locator('table.calendar tr').filter({hasText:'Bolovanje Testni'}).count(),0,'Sick worker hidden from current calendar');
await page.locator('[data-toggle-sick-calendar]').click();
assert.ok(await page.locator('table.calendar tr').filter({hasText:'Bolovanje Testni'}).count(),'Show sick in calendar on demand');
assert.ok(await page.locator('table.calendar tr').filter({hasText:'Bolovanje Testni'}).locator('.cell.BO').count()>0,'Sick leave BO status on scheduled days');
await page.getByRole('button',{name:/Izvještaji/}).first().click();
assert.ok(await page.getByText('Bolovanje Testni').count(),'Sick worker retained in monthly history and reports');
await page.getByRole('button',{name:/Radnici/}).first().click();
await page.locator('tr').filter({hasText:'Bolovanje Testni'}).locator('[data-sick-worker]').click();
await page.locator('[data-sick-edit]').click();
await page.locator('#balkanSickLeaveForm input[name=to]').fill('2026-10-14');
await page.locator('#balkanSickLeaveForm button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('#balkanSickLeaveForm')===null);
await page.getByRole('button',{name:/Kalendar/}).first().click();
assert.ok(await page.locator('table.calendar tr').filter({hasText:'Bolovanje Testni'}).count(),'Worker appears again after sick leave ended');
assert.equal(errors.length,0,'Javascript errors: '+errors.join(' | '));
console.log('PASS Indefinite sick leave: save, suppress warnings, hide/show calendar, BO dates, reports, end date and resume; leave missing-quota notice');
await browser.close();
